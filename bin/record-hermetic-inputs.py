#!/usr/bin/env python3
"""Record topic objects and conflict resolutions needed for offline rebuilds."""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPO = ROOT / "t3code"
DEFAULT_MANIFESTS = (ROOT / "assembly.toml", ROOT / "thread-picker.toml")


def git(*args: str, text: bool = True) -> str | bytes:
    proc = subprocess.run(
        ["git", "-C", str(REPO), *args],
        check=True,
        capture_output=True,
        text=text,
    )
    return proc.stdout.strip() if text else proc.stdout


def label(entry: dict) -> str:
    return f"#{entry['pr']}" if entry.get("pr") else entry["branch"]


def slug(value: str) -> str:
    return re.sub(r"[^a-zA-Z0-9]+", "-", value).strip("-").lower()


def update_manifest_pins(path: Path, lock: dict) -> None:
    """Copy the refreshed base and topic OIDs into the human-owned manifest."""
    lines = path.read_text().splitlines()
    base_replaced = False
    entry_index = -1
    pin_replaced: set[int] = set()
    topic_results = [
        result for result in lock["entries"] if result.get("status") != "epilogue"
    ]

    for line_index, line in enumerate(lines):
        if line.startswith("base = "):
            lines[line_index] = f'base = "{lock["upstream_main"]}"'
            base_replaced = True
        elif line == "[[entry]]":
            entry_index += 1
        elif entry_index >= 0 and line.startswith("pin = "):
            if entry_index >= len(topic_results):
                raise RuntimeError(f"{path.name}: more manifest entries than lock results")
            lines[line_index] = f'pin = "{topic_results[entry_index]["oid"][:12]}"'
            pin_replaced.add(entry_index)

    if not base_replaced:
        raise RuntimeError(f"{path.name}: no base field")
    if len(pin_replaced) != len(topic_results):
        raise RuntimeError(
            f"{path.name}: updated {len(pin_replaced)} pins for "
            f"{len(topic_results)} lock results"
        )
    path.write_text("\n".join(lines) + "\n")


def record_resolutions(manifest_path: Path, manifest: dict, lock: dict) -> None:
    output = ROOT / manifest["resolution_manifest"]
    patch_dir = output.parent / manifest_path.stem
    patch_dir.mkdir(parents=True, exist_ok=True)
    for old_patch in patch_dir.glob("*.patch"):
        old_patch.unlink()

    lines = [
        "# Generated by bin/record-hermetic-inputs.py.",
        "# Each patch is the full first-parent -> resolved-merge diff.",
        "",
    ]
    build = lock["commit"]
    for index, result in enumerate(lock["entries"], start=1):
        if not result.get("conflicted"):
            continue
        entry_label = result["entry"]
        commits = str(
            git(
                "log",
                "--format=%H",
                "--extended-regexp",
                "--grep",
                f"^(assembly|stack): merge {re.escape(entry_label)} ",
                build,
            )
        ).splitlines()
        if not commits:
            raise RuntimeError(f"no merge commit for {entry_label} in {build}")
        merge = commits[0]
        parent = str(git("rev-parse", f"{merge}^1"))
        theirs = str(git("rev-parse", f"{merge}^2"))
        if theirs != result["oid"]:
            raise RuntimeError(
                f"{entry_label}: merge parent {theirs} != lock OID {result['oid']}"
            )

        patch_name = f"{index:02d}-{slug(entry_label)}.patch"
        patch_path = patch_dir / patch_name
        patch_path.write_bytes(
            git(
                "diff",
                "--binary",
                "--full-index",
                parent,
                merge,
                "--",
                text=False,
            )
        )
        relative_patch = patch_path.relative_to(ROOT).as_posix()
        lines.extend(
            [
                "[[resolution]]",
                f"entry = {json.dumps(entry_label)}",
                f"ours_tree = {json.dumps(str(git('rev-parse', f'{parent}^{{tree}}')))}",
                f"theirs = {json.dumps(theirs)}",
                f"resolved_tree = {json.dumps(str(git('rev-parse', f'{merge}^{{tree}}')))}",
                f"patch = {json.dumps(relative_patch)}",
                "",
            ]
        )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines))


def record_bundle(records: list[tuple[Path, dict, dict]]) -> None:
    bundle = ROOT / records[0][1]["topic_bundle"]
    bundle.parent.mkdir(parents=True, exist_ok=True)
    temporary = bundle.with_suffix(".bundle.tmp")
    temporary.unlink(missing_ok=True)

    refs: list[str] = []
    try:
        for manifest_path, manifest, _lock in records:
            for index, entry in enumerate(manifest["entry"], start=1):
                oid = str(git("rev-parse", f"{entry['pin']}^{{commit}}"))
                ref = (
                    f"refs/t3code-assembly/bundle/"
                    f"{manifest_path.stem}/{index:02d}-{slug(label(entry))}"
                )
                git("update-ref", ref, oid)
                refs.append(ref)

        # The submodule supplies the upstream history. The bundle contains
        # every object reachable from a topic tip that is not already reachable
        # from the pinned submodule commit.
        base = str(git("rev-parse", "HEAD"))
        git("bundle", "create", str(temporary), *refs, f"^{base}")
        temporary.replace(bundle)
    finally:
        for ref in refs:
            git("update-ref", "-d", ref)
        temporary.unlink(missing_ok=True)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "manifests",
        nargs="*",
        type=Path,
        default=list(DEFAULT_MANIFESTS),
    )
    args = parser.parse_args()

    records: list[tuple[Path, dict, dict]] = []
    for raw_path in args.manifests:
        path = raw_path if raw_path.is_absolute() else ROOT / raw_path
        lock_path = path.with_suffix(".lock.json")
        lock = json.loads(lock_path.read_text())
        update_manifest_pins(path, lock)
        with path.open("rb") as handle:
            manifest = tomllib.load(handle)
        if manifest["base"] != lock["upstream_main"]:
            raise RuntimeError(
                f"{path.name}: base {manifest['base']} != lock {lock['upstream_main']}"
            )
        for entry, result in zip(manifest["entry"], lock["entries"]):
            if result.get("status") == "epilogue":
                break
            resolved = str(git("rev-parse", f"{entry['pin']}^{{commit}}"))
            if resolved != result["oid"]:
                raise RuntimeError(
                    f"{path.name} {label(entry)}: pin {resolved} != lock {result['oid']}"
                )
        record_resolutions(path, manifest, lock)
        records.append((path, manifest, lock))

    bundles = {record[1]["topic_bundle"] for record in records}
    if len(bundles) != 1:
        raise RuntimeError("all manifests must share one topic_bundle")
    record_bundle(records)
    print(f"recorded {len(records)} manifests in {next(iter(bundles))}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
